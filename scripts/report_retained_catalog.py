"""Report evidence drift for retained theorems; current queues live in the Lean catalog."""

import json
import sys
from pathlib import Path

CATALOG = Path("docs/generated/theorems.json")
OUTPUT = Path("docs/generated")
EVIDENCE = (
    "statement", "module", "compiledConsumers", "simpLemma", "directWrapperOf",
    "terminal", "projectAxioms", "externalAxioms", "directWrapperTargetModule",
    "crossModuleDirectWrapper", "definitionallyEquivalentTo", "replacementCandidates",
    "mathlibDefinitionallyEquivalentTo", "mathlibReplacementCandidates",
    "retainedNeedsReview",
)


def load_baseline(path):
    """A missing or incompatible published snapshot is not a failure of the current audit."""
    try:
        rows = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(rows, list) or any(
            not isinstance(row, dict)
            or not isinstance(row.get("name"), str)
            or not isinstance(row.get("retainedMention"), bool)
            or (row["retainedMention"] and not isinstance(row.get("retainedNeedsReview"), bool))
            for row in rows
        ) or len({row["name"] for row in rows}) != len(rows):
            raise ValueError("incompatible theorem catalog")
        return rows
    except (OSError, UnicodeError, ValueError, TypeError) as exc:
        print(f"::warning::Previous theorem catalog unavailable ({exc}); reporting no drift.",
              file=sys.stderr)
        return None


def compare(current, previous):
    """Only compare formerly/currently retained declarations; do not reproduce Lean queues."""
    result = {"baselineAvailable": previous is not None, "newlyRetained": [],
              "noLongerRetained": [], "lostStructuralSignal": [], "changedReviewEvidence": []}
    if previous is None:
        return result
    now = {row["name"]: row for row in current if row["retainedMention"]}
    old = {row["name"]: row for row in previous if row["retainedMention"]}
    result["newlyRetained"] = sorted(now.keys() - old.keys())
    result["noLongerRetained"] = sorted(old.keys() - now.keys())
    for name in sorted(now.keys() & old.keys()):
        fields = [field for field in EVIDENCE if now[name].get(field) != old[name].get(field)]
        if fields:
            result["changedReviewEvidence"].append({"name": name, "fields": fields})
        if old[name]["retainedNeedsReview"] and not now[name]["retainedNeedsReview"]:
            result["lostStructuralSignal"].append(name)
    return result


def markdown(report):
    lines = ["## Retained theorem evidence drift (advisory)", "",
             "Current retained review queues already appear in `theorems.md` (generated by Lean).",
             "This compares compiled evidence with the published graph-data snapshot, **not**",
             "the last human semantic review; findings never imply automatic deletion.", ""]
    if not report["baselineAvailable"]:
        return "\n".join(lines + ["No compatible baseline available; no historical comparison.", ""])
    labels = (("Newly retained", "newlyRetained"),
              ("No longer retained", "noLongerRetained"),
              ("Lost structural audit signal", "lostStructuralSignal"))
    for label, key in labels:
        lines.append(f"- {label}: **{len(report[key])}**")
    changed = report["changedReviewEvidence"]
    lines.extend([f"- Changed review evidence: **{len(changed)}**", ""])
    for item in changed[:20]:
        lines.append(f"- `{item['name']}`: {', '.join(item['fields'])}")
    if len(changed) > 20:
        lines.append(f"- ... {len(changed) - 20} more (see retained-audit.json)")
    return "\n".join(lines) + "\n"


def main():
    current = json.loads(CATALOG.read_text(encoding="utf-8"))
    baseline = load_baseline(Path(sys.argv[1])) if len(sys.argv) > 1 else None
    report = compare(current, baseline)
    (OUTPUT / "retained-audit.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (OUTPUT / "retained-audit.md").write_text(markdown(report), encoding="utf-8")
    print(f"Retained audit drift: {len(report['changedReviewEvidence'])} changed declarations "
          f"(baseline available: {report['baselineAvailable']})")


if __name__ == "__main__":
    main()
